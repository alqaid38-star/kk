@Client.on_callback_query(filters.regex(r"^hms_reply_(\d+)_(\d+)$"), group=888891)
async def reply_to_hms(client, callback):
    """زر الرد على همسة: يسمح للمستلم بالرد على المرسل الأصلي"""
    data_parts = callback.data.split("_")
    target_user_id = int(data_parts[2])   # المستلم الأصلي (الذي أرسلت له الهمسة)
    hms_id = int(data_parts[3])
    current_user_id = callback.from_user.id

    # التحقق من وجود الهمسة
    if target_user_id not in hms_storage or hms_id not in hms_storage[target_user_id]:
        await callback.answer("⏳ هذه الهمسة غير متوفرة للرد!", show_alert=True)
        return

    # من أرسل الهمسة أصلاً
    original_from_id = hms_storage[target_user_id][hms_id]["from_id"]
    chat_id = hms_storage[target_user_id][hms_id]["chat_id"]

    # يجب أن يكون الضاغط هو المستلم (target_user_id) وليس المرسل
    if current_user_id != target_user_id:
        await callback.answer("🚛 أنت لست مستلم هذه الهمسة، لا يمكنك الرد!", show_alert=True)
        return

    # حفظ سياق الرد لهذا المستخدم
    reply_context[current_user_id] = {
        "to_id": original_from_id,   # الرد سيذهب إلى المرسل الأصلي
        "chat_id": chat_id,
        "original_from_id": original_from_id
    }

    # إرسال رسالة خاصة للمستخدم تطلب منه كتابة الرد
    try:
        await client.send_message(
            chat_id=current_user_id,
            text="📨 **الرد على الهمسة**\n\nأرسل نص أو ميديا (صورة، فيديو، صوت، الخ) للرد على الهمسة التي أرسلها لك الشخص الآخر."
        )
        await callback.answer("✓ تم فتح محادثة خاصة، أرسل ردك الآن", show_alert=True)
        await callback.message.reply_text("✓ تم توجيهك إلى الخاص لإرسال ردّك.")
    except Exception as e:
        await callback.answer(f"فشل فتح المحادثة الخاصة: {e}", show_alert=True)
        await callback.message.reply_text("❌ لا يمكنني مراسلتك في الخاص. تأكد من أنك بدأت المحادثة مع البوت أولاً (اضغط /start).")


